"""(Re)generate the corrected-protocol ("v2") configs, configs/v2_*.yaml.

    python experiments/make_v2_configs.py                       # rewrite the shipped configs (idempotent)
    python experiments/make_v2_configs.py --set train.lr=0.003 --set train.weight_decay=0.01
    python experiments/make_v2_configs.py --out /some/dir       # write elsewhere (used by the tests)

Every v2 config is an existing config with the training protocol corrected: a fixed
epoch budget with early stopping OFF, and (except the deliberate '_dups' condition) pools
without duplicate sequences. `--set section.key=value` applies a change to ALL of them, for the
case where the hyper-parameter study (experiments/tune_hparams.py --summarize) says the
settings used so far should change before the v2 runs are submitted; the change is also
written into each file's header so it cannot be missed later.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
EPOCHS = 150

HEADER = """# CORRECTED-PROTOCOL ("v2") experiment. Every generation is trained for a FIXED
# budget of {epochs} epochs with early stopping OFF (patience: null), on pools
# {pools}.
#
# Why: the first 18+ runs trained with early stopping on validation loss and
# built generation >= 1 pools by sampling WITH replacement (~63% distinct
# sequences). The follow-up experiments showed both choices manufactured much
# of the apparent collapse: retraining first failures without early stopping
# recovered 4 of 6, and removing duplicates cut failures from 22/27 to 1/27.
# {question}
#
# Everything else matches {source}.{overrides}
# Generated by experiments/make_v2_configs.py; edit that script, not this file.
"""

# name, source config, p_synthetic, variant, with_replacement, question
SPECS = [
    ("v2_extended_p1", "extended_collapse.yaml", 1.0, "extended", False,
     "This is the main corrected-protocol test: how much collapse is left at p=1 when neither artifact is present?"),
    ("v2_extended_p05", "ablation_p05.yaml", 0.5, "extended", False,
     "Corrected-protocol mixing-ratio point p=0.5."),
    ("v2_extended_p025", "ablation_p025.yaml", 0.25, "extended", False,
     "Corrected-protocol mixing-ratio point p=0.25."),
    ("v2_base_p1", "base_collapse.yaml", 1.0, "base", False,
     "Corrected-protocol base variant (expected to be near-immune; tests that failures on clean data are seed lottery, not collapse)."),
    ("v2_extended_p1_dups", "extended_collapse.yaml", 1.0, "extended", True,
     "Factorial control: early stopping OFF but duplicates KEPT, so with the original (early stopping ON, duplicates ON) and the no-duplicates runs it separates the two artifacts."),
    ("v2_control_real", "extended_collapse.yaml", 0.0, "extended", False,
     "Real-data control under the SAME protocol: every generation retrains from the same initialisation on a fresh distinct real pool (no synthetic data at all). Whatever changes across generations here is an effect of the training protocol (repeated retraining, fresh pools), not of synthetic data, and is the baseline the synthetic conditions must be compared with."),
]


def set_path(cfg: dict, dotted: str, value) -> None:
    section, key = dotted.split(".", 1)
    if section not in cfg or key not in cfg[section]:
        raise SystemExit(f"--set {dotted}: no such key in the configs")
    cfg[section][key] = value


def build(name, src, p, variant, repl, question, overrides: list[str], config_dir: Path) -> str:
    cfg = yaml.safe_load(open(config_dir / src))
    cfg["train"]["n_epochs"] = EPOCHS
    cfg["train"]["patience"] = None
    cfg["collapse"]["p_synthetic"] = p
    cfg["collapse"]["variant"] = variant
    cfg["collapse"]["with_replacement"] = repl
    cfg["run_name"] = name
    for item in overrides:
        key, raw = item.split("=", 1)
        set_path(cfg, key, yaml.safe_load(raw))
    pools = "WITH duplicates (with-replacement resampling, as in the original runs)" if repl else "WITHOUT duplicate sequences (with_replacement: false)"
    if p == 0.0:
        pools = "of fresh, distinct REAL data only (p_synthetic: 0)"
    note = ("\n# Overrides applied to every v2 config: " + ", ".join(overrides) + ".") if overrides else ""
    header = HEADER.format(epochs=EPOCHS, pools=pools, question=question, source=src, overrides=note)
    return header + yaml.safe_dump(cfg, sort_keys=False, default_flow_style=False)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "configs"))
    ap.add_argument("--set", dest="overrides", action="append", default=[], metavar="section.key=value")
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    for spec in SPECS:
        (out / f"{spec[0]}.yaml").write_text(build(*spec, args.overrides, ROOT / "configs"), encoding="utf-8")
        print("wrote", out / f"{spec[0]}.yaml")


if __name__ == "__main__":
    main()
