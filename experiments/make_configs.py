"""Generate configs/exact_*.yaml (the collapse conditions) with a chosen learning rate and per-generation budget.

    python experiments/make_configs.py --lr 1e-5 --sequences 1000000          # the paper's settings
    python experiments/make_configs.py --lr 1e-4 --sequences 500000 --note "chosen at the tuning gate: ..."

The learning rate and the budget are decided at the tuning gate (analyze_tuning.py); they are recorded in every config's
header so that a later reader can see what was run and why.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent

# name, variant, p_synthetic, what the condition is
CONDITIONS = [
    ("exact_base_p1", "base", 1.0, "base model, fully synthetic: the query label of every real context is re-sampled from the previous model"),
    ("exact_base_p0", "base", 0.0, "base model, real-data control: each generation retrains on the whole real space (the finite space leaves no fresh data)"),
    ("exact_extended_p1", "extended", 1.0, "extended model, fully synthetic"),
    ("exact_extended_p05", "extended", 0.5, "extended model, half synthetic / half fresh real data"),
    ("exact_extended_p025", "extended", 0.25, "extended model, a quarter synthetic"),
    ("exact_extended_p0", "extended", 0.0, "extended model, real-data control: each generation draws a fresh 78,400-sequence real pool"),
]


def build(name, variant, p, desc, lr, sequences, note, eval_every):
    header = (f"# Exact-task collapse condition {name}: {desc}.\n"
              f"# lr {lr:g}, {sequences:,} sequences per generation, 10 generations, same initialisation in every generation of a run.\n"
              f"# loss_weights (lq, S2, l_S2) = (1, 0.1, 0.1) for the extended variant: see src/metrics.py for why not equal.\n"
              f"# Generated by experiments/make_configs.py. {note}\n")
    cfg = {"collapse": {"variant": variant, "p_synthetic": p, "n_generations": 10, "temperature": 1.0, "greedy": False,
                        "sequences": sequences, "lr": lr, "loss_weights": [1.0, 0.1, 0.1], "eval_every": eval_every, "gen_batch_size": 2048}}
    return header + yaml.safe_dump(cfg, sort_keys=False)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--lr", type=float, default=1e-5)
    ap.add_argument("--sequences", type=int, default=1_000_000)
    ap.add_argument("--eval-every", type=int, default=250)
    ap.add_argument("--note", default="Defaults are the paper's (lr 1e-5, 1e6 sequences).")
    ap.add_argument("--out", default=str(ROOT / "configs"))
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    for name, variant, p, desc in CONDITIONS:
        (out / f"{name}.yaml").write_text(build(name, variant, p, desc, args.lr, args.sequences, args.note, args.eval_every), encoding="utf-8")
        print("wrote", out / f"{name}.yaml")


if __name__ == "__main__":
    main()
