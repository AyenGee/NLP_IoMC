"""Generate configs/exact_*.yaml (the collapse conditions) with a chosen learning rate and per-generation budget.

    python experiments/make_configs.py --lr 1e-5 --sequences 1000000          # Tier 1 at the paper's settings
    python experiments/make_configs.py --lr 3e-4 --sequences 160000 --note "chosen at the tuning gate: ..."
    python experiments/make_configs.py --tier2                                # the Tier 2 configs, derived from the Tier 1 ones

The learning rate and the budget are decided at the tuning gate (analyze_tuning.py); they are recorded in every config's
header so that a later reader can see what was run and why. ``--tier2`` reads lr, budget, evaluation interval and loss weights
from the committed configs/exact_base_p1.yaml / exact_extended_p1.yaml (so Tier 2 can never drift from Tier 1) and writes
    exact_{base,extended}_weak{250,500,750,1000,1500}.yaml   weak generator (generation 0 trained for that many steps; 3 generations)
    exact_{base,extended}_{T0p5,T2,Tgreedy}.yaml             sampling temperature 0.5, 2, greedy (fully synthetic, 10 generations)
    exact_{base,extended}_accum.yaml                         accumulate instead of replace (fully synthetic, 10 generations)
    exact_lr1e5_{base_p1,base_p0,extended_p1,extended_p0}.yaml   the paper's lr 1e-5 and 1,000,000 sequences per generation
(continuing Tier 1 chains to generation 20 and the loss-weight sweep need no config file: see experiments/manifest.py).
"""

from __future__ import annotations

import argparse
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent

# name, variant, p_synthetic, what the condition is
CONDITIONS = [
    ("exact_base_p1", "base", 1.0, "base model, fully synthetic: the query label of every real context is re-sampled from the previous model"),
    ("exact_base_p0", "base", 0.0, "base model, real-data control: each generation retrains on the whole real space (the finite space leaves no fresh data)"),
    ("exact_extended_p1", "extended", 1.0, "extended model, fully synthetic"),
    ("exact_extended_p05", "extended", 0.5, "extended model, half synthetic / half fresh real data"),
    ("exact_extended_p025", "extended", 0.25, "extended model, a quarter synthetic"),
    ("exact_extended_p0", "extended", 0.0, "extended model, real-data control: each generation draws a fresh 78,400-sequence real pool"),
]
WEAK_STEPS = [250, 500, 750, 1000, 1500]
TEMPS = {"T0p5": (0.5, False, "sampling temperature 0.5"), "T2": (2.0, False, "sampling temperature 2"), "Tgreedy": (1.0, True, "greedy (argmax) decoding")}


def build(name, variant, p, desc, lr, sequences, note, eval_every, **extra):
    header = (f"# Exact-task collapse condition {name}: {desc}.\n"
              f"# lr {lr:g}, {sequences:,} sequences per generation, {extra.get('n_generations', 10)} generations, same initialisation in every generation of a run.\n"
              f"# loss_weights (lq, S2, l_S2) = (1, 0.1, 0.1) for the extended variant: see src/metrics.py for why not equal.\n"
              f"# Generated by experiments/make_configs.py. {note}\n")
    cfg = {"collapse": {"variant": variant, "p_synthetic": p, "n_generations": 10, "temperature": 1.0, "greedy": False,
                        "sequences": sequences, "lr": lr, "loss_weights": [1.0, 0.1, 0.1], "eval_every": eval_every, "gen_batch_size": 2048}}
    cfg["collapse"].update(extra)
    return header + yaml.safe_dump(cfg, sort_keys=False)


def tier2(out: Path) -> None:
    base = yaml.safe_load((out / "exact_base_p1.yaml").read_text(encoding="utf-8"))["collapse"]
    ext = yaml.safe_load((out / "exact_extended_p1.yaml").read_text(encoding="utf-8"))["collapse"]
    for k in ("lr", "sequences", "eval_every", "loss_weights"):
        assert base[k] == ext[k], f"Tier 1 base and extended configs disagree on {k}"
    lr, seq, ev = base["lr"], base["sequences"], base["eval_every"]
    note = f"Tier 2; lr, budget and evaluation interval are those of the Tier 1 configs (lr {lr:g}, {seq:,} sequences = {seq // 32:,} steps per generation)."
    written = []

    def put(name, variant, p, desc, **extra):
        lr_, seq_ = extra.pop("lr", lr), extra.pop("sequences", seq)
        n_ = note if (lr_, seq_) == (lr, seq) else f"Tier 2; deliberately NOT the Tier 1 settings (Tier 1: lr {lr:g}, {seq:,} sequences per generation)."
        (out / f"{name}.yaml").write_text(build(name, variant, p, desc, lr_, seq_, n_, ev, **extra), encoding="utf-8")
        written.append(name)

    for v in ("base", "extended"):
        for s in WEAK_STEPS:
            put(f"exact_{v}_weak{s}", v, 1.0, f"{v} model, weak-generator test: generation 0 trained for only {s} steps (phase change at about 750-1,750 steps), then 2 generations on its samples",
                n_generations=3, gen0_steps=s)
        for tag, (t, greedy, what) in TEMPS.items():
            put(f"exact_{v}_{tag}", v, 1.0, f"{v} model, fully synthetic with {what}", temperature=t, greedy=greedy)
        put(f"exact_{v}_accum", v, 1.0, f"{v} model, accumulate: generation g trains on a fixed real pool plus the synthetic pools of generations 1..g (Gerstgrasser et al. 2024), instead of replacing", mode="accumulate")
    for name, v, p in [("base_p1", "base", 1.0), ("base_p0", "base", 0.0), ("extended_p1", "extended", 1.0), ("extended_p0", "extended", 0.0)]:
        put(f"exact_lr1e5_{name}", v, p, f"{v} model, p = {p:g}: confirmation at the paper's lr 1e-5 and 1,000,000 sequences (31,250 steps) per generation", lr=1e-5, sequences=1_000_000)
    for n in written:
        print("wrote", out / f"{n}.yaml")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--lr", type=float, default=1e-5)
    ap.add_argument("--sequences", type=int, default=1_000_000)
    ap.add_argument("--eval-every", type=int, default=250)
    ap.add_argument("--note", default="Defaults are the paper's (lr 1e-5, 1e6 sequences).")
    ap.add_argument("--out", default=str(ROOT / "configs"))
    ap.add_argument("--tier2", action="store_true", help="write the Tier 2 configs from the existing Tier 1 ones instead of the Tier 1 configs")
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    if args.tier2:
        tier2(out)
        return
    for name, variant, p, desc in CONDITIONS:
        (out / f"{name}.yaml").write_text(build(name, variant, p, desc, args.lr, args.sequences, args.note, args.eval_every), encoding="utf-8")
        print("wrote", out / f"{name}.yaml")


if __name__ == "__main__":
    main()
