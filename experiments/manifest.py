"""Canonical list of experiment jobs on the exact task, shared by run_array_task.py (one Slurm array task per job) and
check_manifest.py (which verifies every Slurm script's --array range against its group before you submit).

Groups
  tier1       the required collapse experiments (plan section 7, Tier 1 item 3): 6 conditions x 8 seeds = 48 jobs
                exact_base_p1          base, p = 1 (the "reproduce their work, then collapse" condition)
                exact_base_p0          base, real-data control (retrains on the whole real space each generation)
                exact_extended_p1      extended, p = 1
                exact_extended_p05     extended, p = 0.5
                exact_extended_p025    extended, p = 0.25
                exact_extended_p0      extended, real-data control
The configs (configs/exact_*.yaml) are generated by experiments/make_configs.py, which also fixes the learning rate and the
per-generation budget chosen at the tuning gate.
"""

from __future__ import annotations

import dataclasses
from pathlib import Path

CONFIG_DIR = Path(__file__).resolve().parent.parent / "configs"


@dataclasses.dataclass(frozen=True)
class Job:
    config: str          # file name under configs/
    seed: int


TIER1_CONFIGS = ["exact_base_p1.yaml", "exact_base_p0.yaml", "exact_extended_p1.yaml",
                 "exact_extended_p05.yaml", "exact_extended_p025.yaml", "exact_extended_p0.yaml"]
SEEDS = list(range(8))

GROUPS: dict[str, list[Job]] = {
    "tier1": [Job(cfg, s) for cfg in TIER1_CONFIGS for s in SEEDS],
}


def group_jobs(group: str) -> list[Job]:
    if group not in GROUPS:
        raise SystemExit(f"unknown group {group!r}; choose from {sorted(GROUPS)}")
    return GROUPS[group]
