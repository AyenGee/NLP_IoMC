"""Canonical list of experiment jobs on the exact task, shared by run_array_task.py (one Slurm array task per job) and
check_manifest.py (which verifies every Slurm script's --array range and --time against its group before you submit).

Groups (each is one Slurm array job, one task per (condition, seed), one CPU thread per task)
  tier1        the required collapse experiments (plan section 7, Tier 1): 6 conditions x 8 seeds = 48 chains of 10 generations
  weakgen      Tier 2a, weak generator: generation 0 trained for 250/500/750/1000/1500 steps only (before / during / after the
               phase change at lr 3e-4), then 2 further generations on its samples; base and extended, 5 seeds = 50 chains
  continue20   Tier 2b, extend base p=1, base p=0, extended p=1, extended p=0 (8 seeds) from generation 10 to 20, continuing
               from the saved generation-9 checkpoints (the Tier 1 output directories must be in place) = 32 jobs
  temperature  Tier 2c, sampling temperature 0.5, 2 and greedy (T = 1 is Tier 1), both variants, fully synthetic, 5 seeds = 30 chains
  accumulate   Tier 2d, accumulate (real + all earlier synthetic pools) instead of replace, both variants, 8 seeds = 16 chains
  lr1e5        Tier 2e, confirmation at the paper's lr 1e-5 and budget (31,250 steps per generation): base p=1, base p=0,
               extended p=1, extended p=0, 3 seeds, 10 generations = 12 chains
  sweep        Tier 2f, auxiliary-loss weight sweep: extended model, loss weights (1, w, 1) for w in 1, 0.5, 0.3, 0.1, lr 1e-4,
               15,000 steps, 3 seeds = 12 single trainings
The configs (configs/exact_*.yaml) are generated by experiments/make_configs.py (Tier 1 from the tuning gate's lr and budget; the
Tier 2 ones from those, with --tier2). GROUP_INFO holds the array size, the measured local time of one task and the Slurm time
limit (about 1.5 x the measured time, rounded up to 5 minutes), which check_manifest.py compares with each .slurm script.
"""

from __future__ import annotations

import argparse
import dataclasses
import math
from pathlib import Path

CONFIG_DIR = Path(__file__).resolve().parent.parent / "configs"


@dataclasses.dataclass(frozen=True)
class Job:
    config: str                      # file name under configs/ (kind "collapse"), or a label (kind "train")
    seed: int
    overrides: tuple = ()            # ((key, value), ...) applied over the config's fields
    kind: str = "collapse"           # "collapse" (run_collapse) or "train" (one train_model run)
    name: str = ""                   # output name; default <config stem>_s<seed>

    @property
    def run_name(self) -> str:
        return self.name or f"{Path(self.config).stem}_s{self.seed}"


TIER1_CONFIGS = ["exact_base_p1.yaml", "exact_base_p0.yaml", "exact_extended_p1.yaml",
                 "exact_extended_p05.yaml", "exact_extended_p025.yaml", "exact_extended_p0.yaml"]
SEEDS = list(range(8))
VARIANTS = ["base", "extended"]
WEAK_STEPS = [250, 500, 750, 1000, 1500]
TEMPERATURES = ["T0p5", "T2", "Tgreedy"]
CONTINUE_CONFIGS = ["exact_base_p1.yaml", "exact_base_p0.yaml", "exact_extended_p1.yaml", "exact_extended_p0.yaml"]
LR1E5_CONFIGS = ["exact_lr1e5_base_p1.yaml", "exact_lr1e5_base_p0.yaml", "exact_lr1e5_extended_p1.yaml", "exact_lr1e5_extended_p0.yaml"]
SWEEP_S2_WEIGHTS = [1.0, 0.5, 0.3, 0.1]
SWEEP_OVERRIDES = (("variant", "extended"), ("lr", 1e-4), ("steps", 15000), ("sequences", None), ("eval_every", 250))

GROUPS: dict[str, list[Job]] = {
    "tier1": [Job(cfg, s) for cfg in TIER1_CONFIGS for s in SEEDS],
    "weakgen": [Job(f"exact_{v}_weak{k}.yaml", s) for v in VARIANTS for k in WEAK_STEPS for s in range(5)],
    "continue20": [Job(cfg, s, (("n_generations", 20),)) for cfg in CONTINUE_CONFIGS for s in SEEDS],
    "temperature": [Job(f"exact_{v}_{t}.yaml", s) for v in VARIANTS for t in TEMPERATURES for s in range(5)],
    "accumulate": [Job(f"exact_{v}_accum.yaml", s) for v in VARIANTS for s in SEEDS],
    "lr1e5": [Job(cfg, s) for cfg in LR1E5_CONFIGS for s in range(3)],
    "sweep": [Job(f"sweep_s2w{w:g}", s, SWEEP_OVERRIDES + (("loss_weights", (1.0, w, 1.0)),), "train", f"lw3_s2w{w:g}_s{s}")
              for w in SWEEP_S2_WEIGHTS for s in range(3)],
}

# measured minutes of the slowest task of the group on the development machine (4 tasks running at once, one thread each;
# tier 1: base chain 18.4 min, extended chain 28.8 min of 10 generations, i.e. 1.8 / 2.9 min per generation of 5,000 steps)
GROUP_INFO: dict[str, dict] = {
    "tier1": {"est_min": 29, "slurm": "run_tier1.slurm"},
    "weakgen": {"est_min": 7, "slurm": "t2_weakgen.slurm"},             # <= 1,500 + 2 x 5,000 steps (extended)
    "continue20": {"est_min": 33, "slurm": "t2_continue20.slurm"},       # 10 more generations (+ replay of the sampling draws)
    "temperature": {"est_min": 29, "slurm": "t2_temperature.slurm"},
    "accumulate": {"est_min": 30, "slurm": "t2_accumulate.slurm"},
    "lr1e5": {"est_min": 106, "slurm": "t2_lr1e5.slurm"},                # 10 x 31,250 steps at 51 steps/s (extended)
    "sweep": {"est_min": 6, "slurm": "t2_sweep.slurm"},                  # 15,000 steps at 51 steps/s (extended)
}
TIME_MARGIN = 1.5


def time_limit_minutes(group: str, scale: float = 1.0) -> int:
    return int(math.ceil(TIME_MARGIN * scale * GROUP_INFO[group]["est_min"] / 5.0) * 5)


def time_limit(group: str, scale: float = 1.0) -> str:
    m = time_limit_minutes(group, scale)
    return f"{m // 60:02d}:{m % 60:02d}:00"


def group_jobs(group: str) -> list[Job]:
    if group not in GROUPS:
        raise SystemExit(f"unknown group {group!r}; choose from {sorted(GROUPS)}")
    return GROUPS[group]


if __name__ == "__main__":      # python3 experiments/manifest.py --time weakgen [--scale 1.5]   |   --list weakgen
    ap = argparse.ArgumentParser()
    ap.add_argument("--time", metavar="GROUP")
    ap.add_argument("--size", metavar="GROUP")
    ap.add_argument("--scale", type=float, default=1.0)
    ap.add_argument("--list", metavar="GROUP")
    ap.add_argument("--find", nargs=2, metavar=("GROUP", "RUN_NAME"), help="print the array task id of a run name")
    a = ap.parse_args()
    if a.find:
        names = [j.run_name for j in group_jobs(a.find[0])]
        if a.find[1] not in names:
            raise SystemExit(f"{a.find[1]!r} is not in group {a.find[0]!r}")
        print(names.index(a.find[1]))
    elif a.time:
        print(time_limit(a.time, a.scale))
    elif a.size:
        print(len(group_jobs(a.size)))
    elif a.list:
        for i, j in enumerate(group_jobs(a.list)):
            print(i, j.run_name, j.config, j.overrides)
